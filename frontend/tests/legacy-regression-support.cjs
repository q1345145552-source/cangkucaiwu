async function verifyMoneyIdentity(h, amount, day) {
  const walk = x => !x || typeof x !== 'object' ? [] : Array.isArray(x) ? x.flatMap(walk) : [x, ...walk(x.props?.children)];
  const text = x => x == null || typeof x === 'boolean' ? '' : typeof x !== 'object' ? String(x) : Array.isArray(x) ? x.map(text).join('') : text(x.props?.children);
  const button = (tree, label) => {const n = walk(tree).find(n => n.type === 'button' && text(n) === label); assert(n, label); return n;};
  const labelled = (tree, label) => {const n = walk(tree).find(n => n.props?.['aria-label'] === label); assert(n, label); return n;};
  const change = (node, value) => node.props.onChange({target: {value}});
  function field(tree, label) {
    const box = walk(tree).find(n => n.type === 'div' && React.Children.toArray(n.props.children).some(c => c.type === 'label' && text(c) === label));
    assert(box, label); return walk(box).find(n => ['input', 'select'].includes(n.type));
  }
  let tree = await h.render();
  button(tree, '付款').props.onClick(); tree = await h.render();
  button(tree, '新建记录').props.onClick(); tree = await h.render();
  const wid = Number(h.flags.warehouse);
  const suppliers = walk(labelled(tree, '费用供应商')).filter(n => n.type === 'option');
  assert.deepEqual(suppliers.map(n => n.props.value), [0, wid * 10 + 1], 'Only selected-warehouse suppliers offered');
  change(labelled(tree, '费用供应商'), String(wid * 10 + 1)); tree = await h.render();
  for (const [label, value] of [['开票方官方识别号', 'SYNTHETIC-TAX'], ['发票类型／系列', 'VAT'], ['完整发票号码', `W${wid}-ONLY`]]) {
    change(labelled(tree, label), value); tree = await h.render();
  }
  for (const [label, value] of [['类别', '1'], ['收款账户', String(wid * 10 + 2)], ['日期', day], ['金额', String(amount)]]) {
    change(field(tree, label), value); tree = await h.render();
  }
  await button(tree, '保存').props.onClick(); tree = await h.render();
  assert.equal(h.writes.length, 0, 'Unverified identity must prevent the actual wallet request');
  assert(h.messages.some(m => String(m[1]).includes('核对完整发票')));
  walk(tree).find(n => n.type === 'input' && n.props.type === 'checkbox').props.onChange({target: {checked: true}});
  tree = await h.render(); await button(tree, '保存').props.onClick(); tree = await h.render();
  assert.equal(h.writes.length, 1);
  const written = h.writes[0];
  assert.equal(written.headers['X-Warehouse-ID'], String(wid));
  assert.equal(written.headers.Authorization, 'Bearer synthetic-test-token');
  assert.equal(Number(written.body.amount), amount);
  assert.equal(written.body.expense_date, day);
  assert.equal(Number(written.body.supplier_id), wid * 10 + 1);
  assert.equal(Number(written.body.account_id), wid * 10 + 2);
  assert.deepEqual(JSON.parse(written.body.invoice_identity), {issuer_identifier: 'SYNTHETIC-TAX', series: 'VAT', number: `W${wid}-ONLY`, verified: true});
  assert.match(written.body.request_key, /^isolated-wallet-/);
  assert(h.scopes.some(r => r.route === '/expense-identities/suppliers' && r.warehouse === String(wid)));
}
