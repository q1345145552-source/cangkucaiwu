// Compile production modules; only browser/transport boundaries are supplied by tests.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const root = path.resolve(__dirname, '../..');
function compile(source, imports = {}, globals = {}, fileName = "module.tsx") {
  const mod = {exports: {}};
  const code = ts.transpileModule(source, {fileName, compilerOptions: {
    module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020,
    jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true,
  }}).outputText;
  vm.runInNewContext(code, {module: mod, exports: mod.exports,
    require: name => imports[name] || require(name), console, ...globals});
  return mod.exports;
}
function moduleFrom(file, imports, globals) {
  return compile(fs.readFileSync(path.join(root, file), 'utf8'), imports, globals, file);
}
function runtimeHandlers(source, file, excluded) {
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const out = {};
  function visit(node) {
    if (ts.isFunctionDeclaration(node) && node.name && !excluded.includes(node.name.text)) {
      out[node.name.text] = ts.transpileModule(node.getText(sf), {
        compilerOptions: {target: ts.ScriptTarget.ES2020},
      }).outputText;
    }
    ts.forEachChild(node, visit);
  }
  visit(sf);
  return out;
}
function actualFunction(source, file, name, globals) {
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  let found;
  function visit(node) {
    if (ts.isFunctionDeclaration(node) && node.name?.text === name) found = node;
    ts.forEachChild(node, visit);
  }
  visit(sf); assert(found, `Missing production function ${name}`);
  return compile(found.getText(sf) + `\nmodule.exports = ${name};`, {}, globals);
}
function menuContract(key, href) {
  // Read the single backend registry, never keep a duplicate permission catalogue.
  assert(process.env.INVENTORY_REGISTRY_FILE, 'Run with the generated backend registry fixture');
  const registry = JSON.parse(fs.readFileSync(process.env.INVENTORY_REGISTRY_FILE, 'utf8'));
  // Export pure production gates without changing the shipped module.
  const source = fs.readFileSync(path.join(root, 'frontend/src/components/layout/DashboardLayout.tsx'), 'utf8');
  const {filterNavItems, navItems} = compile(source + '\nexport {filterNavItems, navItems};', {
    react: React, 'next/navigation': {}, 'next/link': {__esModule: true, default: 'a'},
    '@/hooks/useI18n': {}, '@/lib/api': {}, '@/components/ui/BackToTop': {default: () => null},
  });
  const entry = registry.find(p => p.menu_key === key); assert(entry?.selectable);
  assert.equal(entry.path, href);
  const leaves = items => items.flatMap(i => i.children ? leaves(i.children) : [i]);
  for (const role of ['warehouse_admin', 'super_admin', 'supervisor', 'staff', 'warehouse_labor']) {
    for (const grant of [false, true]) {
      const visible = leaves(filterNavItems(navItems, {id: 1, role, extra_permissions: grant ? [entry.label] : []}, registry));
      const allowed = role === 'warehouse_admin' || (grant && ['supervisor', 'staff'].includes(role))
        || (role === 'super_admin' && key === 'modification_logs');
      assert.equal(visible.some(i => i.key === key && i.href === href), allowed, `${key} ${role} grant=${grant}`);
      assert(!visible.some(i => ['/reports/operations', '/customer-receivables', '/customer-shipments'].includes(i.href)));
    }
  }
}
